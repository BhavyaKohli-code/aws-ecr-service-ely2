-- Agency sales KPI schema for Bedrock POC (matches data/bedrock_data_poc_*.csv)
-- Remove deprecated ecommerce warehouse schema (no longer used).
DROP SCHEMA IF EXISTS ecomm CASCADE;

CREATE SCHEMA IF NOT EXISTS agency;

DROP TABLE IF EXISTS agency.agent_kpi;
DROP TABLE IF EXISTS agency.agent_hierarchy;

CREATE TABLE agency.agent_hierarchy (
    agent_id VARCHAR(32) NOT NULL,
    agent_name VARCHAR(255),
    master_flag VARCHAR(32),
    master_role VARCHAR(64),
    master_dsg VARCHAR(32),
    agent_branch VARCHAR(32),
    agt_desg_desc VARCHAR(255),
    aap_1 VARCHAR(32),
    aap_2 VARCHAR(32),
    aap_3 VARCHAR(32),
    adm VARCHAR(32),
    ap VARCHAR(32),
    partner VARCHAR(32),
    oh BIGINT,
    rm BIGINT,
    zh BIGINT,
    ch BIGINT,
    supervisor_id BIGINT,
    supervisor_name VARCHAR(255),
    supervisor_role VARCHAR(32),
    agent_status VARCHAR(32),
    arm_id VARCHAR(32),
    super_zvp_id BIGINT,
    super_zvp_name VARCHAR(255),
    relationship_to_office_head VARCHAR(64),
    PRIMARY KEY (agent_id)
);

